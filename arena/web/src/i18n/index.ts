const saved = localStorage.getItem("arena.locale");
const browser = navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";

void i18next.use(initReactI18next).init({
  resources: { zh: { translation: zh }, en: { translation: en } },
  lng: languages.includes(saved as Locale) ? (saved as Locale) : browser,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export function setLocale(locale: Locale) {
  localStorage.setItem("arena.locale", locale);
  void i18next.changeLanguage(locale);
}

export default i18next;
